export const components: SystemComponent[] = categories.flatMap((category) =>
  groups[category].map(([id, name, description, icon, tone, brand]) => ({
    id,
    name,
    description,
    icon,
    category,
    color: palette[tone][0],
    fill: palette[tone][1],
    brand,
  })),
)
export const componentById = Object.fromEntries(components.map((c) => [c.id, c])) as Record<
  string,
  SystemComponent
>
export function searchComponents(query: string, category?: Category) {
  const words = query.trim().toLowerCase().split(/\s+/)
  return components.filter(
    (c) =>
      (!category || c.category === category) &&
      words.every((word) =>
        `${c.name} ${c.description} ${c.category}`.toLowerCase().includes(word),
      ),
  )
}
